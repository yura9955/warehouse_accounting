# ---------------------------------------------------------------------------
# Конфигурация расчёта прогноза
# ---------------------------------------------------------------------------

# Веса компонент итоговой уверенности (confidence). Сумма = 1.0.
#   history    — чем длиннее история, тем выше доверие к модели.
#   volatility — чем стабильнее расход, тем выше доверие.
#   backtest   — насколько EMA точно предсказывала прошлые недели (MAPE).
#   agreement  — насколько EMA и линейно-сезонная модель согласны.
#   horizon    — чем длиннее горизонт, тем ниже уверенность.
# Backtest и history получают наибольший вес, потому что это прямые
# метрики качества модели, а не косвенные эвристики.
WEIGHTS: dict[str, float] = {
    "history": 0.25,
    "volatility": 0.15,
    "backtest": 0.25,
    "agreement": 0.15,
    "horizon": 0.20,
}

# Длина сезонного цикла в неделях. 12 недель ≈ квартал — минимальный
# горизонт, на котором имеет смысл выделять сезонную компоненту.
# Если истории меньше PERIOD недель, сезонность не выделяется вовсе.
PERIOD: int = 12

# Минимальная длина истории (в неделях) для подключения линейно-сезонной
# модели. Короче — модель доверяет только EMA, потому что на 20–30 неделях
# тренд и сезонность оцениваются неустойчиво.
MIN_WEEKS: int = 52

# Масштабный коэффициент для компоненты уверенности по горизонту.
# Задаёт точку, где уверенность падает до 0.5: при horizon = SCALE_DAYS
# формула 1 / (1 + horizon / SCALE_DAYS) даёт ровно 0.5.
SCALE_DAYS: float = 90.0